#!/usr/bin/env python3
"""Build Hugo in a temporary directory, then refresh the Pages publishing root."""

import os
from pathlib import Path
import shutil
import subprocess
import tempfile


def main():
    root = Path(__file__).resolve().parents[1]
    if (root / ".nojekyll").exists():
        raise SystemExit(
            "Remove the root .nojekyll: GitHub Pages needs _config.yml exclusions "
            "to omit Hugo sources and duplicate output."
        )

    # Hugo regenerates this editor-only file with machine-specific cache paths.
    jsconfig = root / "assets/jsconfig.json"
    original_jsconfig = jsconfig.read_bytes() if jsconfig.exists() else None
    try:
        with tempfile.TemporaryDirectory(prefix="xinyu-pages-") as temporary:
            staging = Path(temporary)
            output = staging / "public"
            env = os.environ.copy()
            env["HUGO_RESOURCEDIR"] = str(staging / "resources")
            subprocess.run(
                [
                    "hugo",
                    "--environment", "production",
                    "--destination", str(output),
                    "--noBuildLock",
                ],
                cwd=root,
                env=env,
                check=True,
            )
            if not (output / "index.html").is_file():
                raise SystemExit("Hugo did not produce index.html; publishing root unchanged.")

            # Overlay only after a successful build. Keep standalone project pages
            # and other files that are not generated by this Hugo project.
            shutil.copytree(
                output,
                root,
                dirs_exist_ok=True,
                copy_function=shutil.copyfile,
                ignore=shutil.ignore_patterns(".DS_Store"),
            )
    finally:
        if original_jsconfig is not None:
            jsconfig.write_bytes(original_jsconfig)
        elif jsconfig.exists():
            jsconfig.unlink()

    print("Updated the GitHub Pages publishing root. Review, commit, and push the changes.")


if __name__ == "__main__":
    main()
